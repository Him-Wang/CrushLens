            session.Provider = "示例数据";
            session.Model = "demo";
            session.AnalysisLimit = 120;
            session.CreatedAt = TimeUtil.NowMs();
            session.UpdatedAt = session.CreatedAt;
            session.Messages = parsed.Messages;
            session.IsDemo = true;
            session.Stats = StatsEngine.Compute(session.Messages, session.MeName, session.CrushName);
            session.Report = CreateReport(session);
